import { useEffect, useState } from 'react';
import { api, Issue, Analysis } from '../api/client';

interface IssueDetailProps {
  issue: Issue | null;
}

export function IssueDetail({ issue }: IssueDetailProps) {
  const [analysis, setAnalysis] = useState<Analysis | null>(null);
  const [analyses, setAnalyses] = useState<Analysis[]>([]);
  const [analyzing, setAnalyzing] = useState(false);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    if (issue) {
      loadAnalyses();
    } else {
      setAnalysis(null);
      setAnalyses([]);
    }
  }, [issue]);

  const loadAnalyses = async () => {
    if (!issue) return;
    try {
      const data = await api.issues.analyses(issue.id);
      setAnalyses(data);
      if (data.length > 0) setAnalysis(data[0]);
    } catch {
      // Ignore error, just show no analyses
    }
  };

  const handleAnalyze = async () => {
    if (!issue) return;
    setAnalyzing(true);
    setError(null);
    try {
      const newAnalysis = await api.issues.analyze(issue.id);
      setAnalysis(newAnalysis);
      setAnalyses((prev) => [newAnalysis, ...prev]);
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Analysis failed');
    } finally {
      setAnalyzing(false);
    }
  };

  if (!issue) {
    return (
      <div className="issue-detail-empty">
        <p>Select an issue from the list to view details</p>
      </div>
    );
  }

  return (
    <div className="issue-detail">
      <div className="issue-detail-header">
        <h2>
          <a href={issue.html_url} target="_blank" rel="noopener noreferrer">
            #{issue.id}: {issue.title}
          </a>
        </h2>
        <div className="issue-meta">
          <span className={`status-badge ${issue.state}`}>{issue.state}</span>
          <span>Author: {issue.author_html_url ? <a href={issue.author_html_url} target="_blank" rel="noopener noreferrer">{issue.author_login}</a> : issue.author_login}</span>
          <span>Updated: {new Date(issue.updated_at).toLocaleDateString()}</span>
          <span>Comments: {issue.comments_count}</span>
        </div>
        <div className="issue-labels">
          {issue.labels.map((label) => (
            <span key={label} className="label-badge">{label}</span>
          ))}
        </div>
      </div>

      <div className="issue-body">
        <h3>Description</h3>
        <div className="issue-body-content" dangerouslySetInnerHTML={{ __html: issue.body || '<em>No description</em>' }} />
      </div>

      {issue.comments && issue.comments.length > 0 && (
        <div className="issue-comments">
          <h3>Comments ({issue.comments.length})</h3>
          {issue.comments.slice(-5).map((comment, index) => (
            <div key={index} className="comment">
              <div className="comment-header">
                <strong>{comment.user.login}</strong>
                <span>{new Date(comment.created_at).toLocaleDateString()}</span>
              </div>
              <div className="comment-body" dangerouslySetInnerHTML={{ __html: comment.body }} />
            </div>
          ))}
          {issue.comments.length > 5 && (
            <p className="comments-truncated">
              Showing latest 5 of {issue.comments.length} comments.{' '}
              <a href={issue.html_url} target="_blank" rel="noopener noreferrer">
                View all on GitHub
              </a>
            </p>
          )}
        </div>
      )}

      <div className="issue-analysis">
        <h3>AI Analysis</h3>
        <p className="advisory-notice">⚠️ Advisory only — generated by LLM, not verified</p>

        {analysis ? (
          <div className="analysis-content">
            <div className="analysis-section">
              <h4>Summary</h4>
              <p>{analysis.summary}</p>
            </div>

            {analysis.key_points.length > 0 && (
              <div className="analysis-section">
                <h4>Key Points</h4>
                <ul>
                  {analysis.key_points.map((point, i) => (
                    <li key={i}>{point}</li>
                  ))}
                </ul>
              </div>
            )}

            {analysis.blockers.length > 0 && (
              <div className="analysis-section">
                <h4>Blockers</h4>
                <ul>
                  {analysis.blockers.map((blocker, i) => (
                    <li key={i}>{blocker}</li>
                  ))}
                </ul>
              </div>
            )}

            {analysis.unresolved_questions.length > 0 && (
              <div className="analysis-section">
                <h4>Unresolved Questions</h4>
                <ul>
                  {analysis.unresolved_questions.map((q, i) => (
                    <li key={i}>{q}</li>
                  ))}
                </ul>
              </div>
            )}

            <div className="analysis-meta">
              <small>
                Provider: {analysis.provider} | Model: {analysis.model} |{' '}
                Generated: {new Date(analysis.created_at).toLocaleString()}
              </small>
            </div>
          </div>
        ) : (
          <p className="no-analysis">No analysis available yet.</p>
        )}

        <button
          onClick={handleAnalyze}
          disabled={analyzing}
          className="analyze-button"
        >
          {analyzing ? 'Analyzing...' : analysis ? 'Re-analyze' : 'Analyze with AI'}
        </button>

        {error && <div className="error-message">Error: {error}</div>}
      </div>

      {analyses.length > 1 && (
        <div className="analysis-history">
          <h4>Analysis History</h4>
          <ul>
            {analyses.map((a) => (
              <li key={a.id}>
                <small>
                  {new Date(a.created_at).toLocaleString()} — {a.provider}/{a.model}
                </small>
              </li>
            ))}
          </ul>
        </div>
      )}
    </div>
  );
}